import pandas as pd
import numpy as np
import seaborn as sns
import matplotlib.pyplot as plt

def load_data():
    url = 'https://raw.githubusercontent.com/huynhhoc/DataAnalystDeepLearning/refs/heads/main/Data/babies.csv'
    return pd.read_csv(url, sep='\s+')

df = load_data()

# --- 1. XỬ LÝ DỮ LIỆU THIẾU (MISSING DATA) ---
# Trong bộ dữ liệu này, đôi khi giá trị thiếu được ký hiệu là số 999 hoặc 99
# Ta cần đưa chúng về dạng NaN để xử lý thống nhất
df.replace([999, 99], np.nan, inplace=True)

# Cách A: Xóa các dòng có bất kỳ ô nào trống (Đúng yêu cầu "đầy đủ dữ liệu" của bạn)
df_clean = df.dropna()

print(f"Kích thước ban đầu: {df.shape}")
print(f"Kích thước sau khi xóa dữ liệu thiếu: {df_clean.shape}")

# --- 2. XỬ LÝ OUTLIER (GIÁ TRỊ NGOẠI LAI) ---

Q1 = df_clean['bwt'].quantile(0.25)
Q3 = df_clean['bwt'].quantile(0.75)
IQR = Q3 - Q1

lower_bound = Q1 - 1.5 * IQR
upper_bound = Q3 + 1.5 * IQR

# Lọc bỏ các giá trị nằm ngoài khoảng này
df_final = df_clean[(df_clean['bwt'] >= lower_bound) & (df_clean['bwt'] <= upper_bound)]

print(f"Kích thước sau khi loại Outliers: {df_final.shape}")

# --- 3. TRỰC QUAN HÓA ĐỂ KIỂM TRA ---
plt.figure(figsize=(12, 5))

plt.subplot(1, 2, 1)
sns.boxplot(y=df_clean['bwt'])
plt.title('Trước khi xử lý Outlier')

plt.subplot(1, 2, 2)
sns.boxplot(y=df_final['bwt'])
plt.title('Sau khi xử lý Outlier')

plt.show()
def thuc_thi_bai_tap(so_bai):
    if so_bai == 1:
        print("\n[Bai 1] Kiem tra tat ca phan tu khac 0")
        mang = np.random.randint(0, 21, size=(3, 3))
        print("Mang:\n", mang)
        print("Tat ca khac 0:", np.all(mang != 0))

    elif so_bai == 2:
        print("\n[Bai 2] Kiem tra ton tai it nhat mot phan tu khac 0")
        mang = np.random.randint(0, 21, size=(3, 3))
        print("Mang:\n", mang)
        print("Ton tai phan tu khac 0:", np.any(mang != 0))

    elif so_bai == 3:
        print("\n[Bai 3] So sanh hai mang")
        m1, m2 = np.array([1, 5]), np.array([2, 4])
        print(f"m1: {m1}, m2: {m2}")
        print("Lon hon:", np.greater(m1, m2))
        print("Nho hon hoac bang:", np.less_equal(m1, m2))

    elif so_bai == 4:
        print("\n[Bai 4] Tao mang 10 so 1, 10 so 0, 10 so 5")
        kq = np.concatenate([np.ones(10), np.zeros(10), np.full(10, 5)])
        print(kq)

    elif so_bai == 5:
        print("\n[Bai 5] Mang so chan trong khoang [30, 70]")
        print(np.arange(30, 71, 2))

    elif so_bai == 6:
        print("\n[Bai 6] Ma tran don vi 3x3")
        print(np.identity(3))

    elif so_bai == 7:
        print("\n[Bai 7] Mang 10 phan tu [15, 55], loai dau va cuoi")
        mang = np.linspace(15, 55, 10)
        print("Goc:", mang)
        print("Ket qua:", mang[1:-1])

    elif so_bai == 8:
        print("\n[Bai 8] Dao dau cac so tu 9 den 15")
        mang = np.arange(21)
        mang[(mang >= 9) & (mang <= 15)] *= -1
        print(mang)

    elif so_bai == 9:
        print("\n[Bai 9] Ma tran 3x4 gia tri tu 10 den 21")
        print(np.random.randint(10, 22, size=(3, 4)))

    elif so_bai == 10:
        print("\n[Bai 10] Ma tran 10x10 vien 1, trong 0")
        mang = np.ones((10, 10))
        mang[1:-1, 1:-1] = 0
        print(mang)

    elif so_bai == 11:
        print("\n[Bai 11] Duong cheo chinh la 1, 2, 3, 4, 5")
        print(np.diag([1, 2, 3, 4, 5]))

    elif so_bai == 12:
        print("\n[Bai 12] Tong theo cot cua mang 3x3x3")
        mang = np.random.randint(1, 10, size=(3, 3, 3))
        print("Tong (axis 0):\n", mang.sum(axis=0))

    elif so_bai == 13:
        print("\n[Bai 13] Tich vo huong 2 vector")
        v1, v2 = np.random.rand(10), np.random.rand(10)
        print("Dot product:", np.dot(v1, v2))

    elif so_bai == 14:
        print("\n[Bai 14] Cong vector vao tung dong ma tran")
        M = np.random.rand(4, 3)
        v = np.random.rand(3)
        print("Ket qua:\n", M + v)

    elif so_bai == 15:
        print("\n[Bai 15] Phep cong tren 2 Series")
        ds1 = pd.Series([2, 4, 6, 8, 10])
        ds2 = pd.Series([1, 3, 5, 7, 10])
        print("Tong:\n", ds1 + ds2)

    elif so_bai == 16:
        print("\n[Bai 16] Trich xuat cot dau thanh Series")
        du_lieu = pd.DataFrame({'c1': [1, 4, 7], 'c2': [2, 5, 8], 'c3': [3, 6, 9]})
        print(du_lieu.iloc[:, 0])

    elif so_bai == 17:
        print("\n[Bai 17] Sap xep DataFrame theo cot A")
        du_lieu = pd.DataFrame(np.random.rand(4, 3), columns=['A', 'B', 'C'])
        print(du_lieu.sort_values(by='A'))

    elif so_bai == 18:
        print("\n[Bai 18] Thay doi thu tu index cua Series")
        ds = pd.Series([1, 2, 3], index=['A', 'B', 'C'])
        print(ds.reindex(['B', 'A', 'C']))

    elif so_bai == 19:
        print("\n[Bai 19] Tim phan tu co trong s1 nhung khong co trong s2")
        s1, s2 = pd.Series([1, 2, 3, 4, 5]), pd.Series([2, 4, 6, 8])
        print(s1[~s1.isin(s2)])

    elif so_bai == 20:
        print("\n[Bai 20] Tim tap hop Hoi va Giao")
        m1 = np.random.randint(0, 10, 20)
        m2 = np.random.randint(0, 10, 20)
        print("Hoi (Union):", np.union1d(m1, m2))
        print("Giao (Intersect):", np.intersect1d(m1, m2))

    elif so_bai == 21:
        print("\n[Bai 21] Noi Series theo chieu doc va ngang")
        s_a, s_b = pd.Series([0, 1, 2]), pd.Series(['p', 'q', 'r'])
        print("Noi doc:\n", pd.concat([s_a, s_b], axis=0))
        print("Noi ngang:\n", pd.concat([s_a, s_b], axis=1))

    # Du lieu mau cho bai 22-30
